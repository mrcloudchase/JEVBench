"""Stage 4, report: scores -> tables. Reads scores/<experiment>.json only; writes reports/<experiment>.md
and one CSV per task. Never edit the outputs by hand: change the code or the runs, then regenerate."""

from __future__ import annotations

import csv
import json

METRICS = ("accuracy", "precision", "recall", "f1", "auroc", "macro_f1", "within_one", "mae", "brier", "ece", "agree")


def fmt(value, digits=3):
    if value is None:
        return "-"
    if isinstance(value, (list, tuple)):
        return f"{value[0]:.{digits}f}–{value[1]:.{digits}f}"
    return f"{value:.{digits}f}" if isinstance(value, float) else str(value)


def table(entry: dict) -> list[str]:
    runs = entry["runs"]
    keys = [k for k in METRICS if k in runs[0]]
    head = ["model", "served", "n", "repeats", *keys, "$ per 1k", "tokens", "p50 ms", "p95 ms", "errors", "refusals"]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in runs:
        cells = [r["model"], r["name"].split(" ", 1)[1], r["n"], r["repeats"]]
        cells += [fmt(r[k]) + (f" ({fmt(r[k + '_range'])})" if r.get(k + "_range") else "") for k in keys]
        cells += [fmt(r["usd_per_1k"], 4), f"{r['tokens_per_item']:.0f}", fmt(r["latency_p50_ms"], 0),
                  fmt(r["latency_p95_ms"], 0), r["errors"], r["refusals"]]
        lines.append("| " + " | ".join(str(c) for c in cells) + " |")
    return lines


def render(scores: dict) -> str:
    lines = [f"# {scores['experiment']}", "", "Generated by `tdm report` from `scores/"
             f"{scores['experiment']}.json`. Do not edit by hand."]
    for task, entry in scores["tasks"].items():
        lines += ["", f"## {task}", ""]
        if not entry["runs"]:
            lines.append(f"No complete runs yet (missing: {', '.join(entry['missing'])}).")
            continue
        lines.append(f"Task version `{entry['task_version']}`, question `{entry['question']}`, scorer {entry['type']}"
                     + (f", threshold {entry['threshold']}" if entry["type"] == "noul" else "") + ".")
        if entry["missing"]:
            lines.append(f"Missing runs: {', '.join(entry['missing'])}.")
        lines += [""] + table(entry)
        if entry["paired"]:
            lines += ["", f"Accuracy versus {entry['base']} on the same records (first repeat; 95% paired bootstrap):", "",
                      "| model | n | delta | ci95 | only base right | only other right |", "|---|---|---|---|---|---|"]
            lines += [f"| {d['model']} | {d['n']} | {d['delta']:+.3f} | {fmt(d['ci95'])} | {d['only_base_right']} | {d['only_other_right']} |"
                      for d in entry["paired"]]
    return "\n".join(lines) + "\n"


def report_experiment(project, name: str) -> str:
    scores = json.loads((project.root / "scores" / f"{name}.json").read_text())
    out = project.root / "reports"
    out.mkdir(exist_ok=True)
    text = render(scores)
    (out / f"{name}.md").write_text(text, encoding="utf-8")
    for task, entry in scores["tasks"].items():
        if entry["runs"]:
            with (out / f"{name}.{task}.csv").open("w", newline="", encoding="utf-8") as f:
                fields = ["model", "run", "n", "repeats", *[k for k in METRICS if k in entry["runs"][0]],
                          "usd_per_1k", "tokens_per_item", "latency_p50_ms", "latency_p95_ms", "errors", "refusals"]
                writer = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
                writer.writeheader()
                writer.writerows(entry["runs"])
    return text
